"""Canary Sweep — find which input fields STORE attacker text intact, before spending any payload.

WHY THIS EXISTS
  Hunt #37 mapped 1041 input fields and 176 usable payloads. Firing every payload at every field is
  ~35k requests: that is scanning, it is slow, and most of it teaches nothing because a field that
  coerces, truncates or rejects its input can never carry an injection anyway.

  So pass 1 sends ONE unique marker per field, grouped so a whole input object is written in a
  single request, then reads every field back and sorts them:

    STORED-INTACT   the marker came back byte-for-byte      -> pass 2 spends real payloads here
    TRANSFORMED     encoded, stripped, truncated, coerced   -> record what the transform was
    REJECTED        the write failed or the field is absent -> nothing to attack
    UNREADABLE      no read path for this field             -> never "clean", just unmeasured

  Two orders of magnitude fewer requests, and every result is readable.

THE RULE THIS ENFORCES
  A field is only sorted when it has a PROVEN READ PATH. Writing a marker you cannot read back is
  not a test — it is a write with no oracle, and counting it as covered is how a class gets marked
  green while untested. Families without a verified read query are emitted as UNREADABLE by
  construction, never omitted silently.

  Storage is a LEAD, not a verdict: a marker surviving intact says the value round-trips, NOT that
  it is injectable. Only a human seeing the rendered DOM closes an XSS.

Offline, stdlib-only. Generates a batch; sends nothing itself.
"""
