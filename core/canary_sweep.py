def build(surface, input_name, host, variables, mutation, read_query, base,
          include_coercing=False, var_name="input", dig="null"):
    """`var_name` = the GraphQL variable the input object rides in.
    `dig` = a JS expression over `be` (the baseEntity) returning the object to read fields back from.
    """
    split = fields_for(surface, input_name)
    obj, planted, skipped = marker_object(split, base=base, include_coercing=include_coercing)
    js = (JS.replace("__HOST__", host)
            .replace("__VARS__", json.dumps(variables))
            .replace("__PLANTED__", json.dumps(planted))
            .replace("__BASE__", json.dumps(base))
            .replace("__MUT__", json.dumps(mutation))
            .replace("__READ__", json.dumps(read_query))
            .replace("__VARNAME__", var_name)
            .replace("__DIG__", dig))
    return js, split, planted, skipped
