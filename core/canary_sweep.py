# Types whose values can carry text at all. A Rupee or Boolean field cannot hold a payload, so
# marking one is a wasted request — but its COERCION behaviour is still worth one probe, which is
# why the numeric families are listed separately rather than dropped.
TEXTUAL = {"String", "Byte"}
COERCING = {"Rupee", "Decimal", "Percent", "PreciseRupee", "MoneyEx", "Int", "Long",
            "DateTimeWrapper", "TimeStampWrapper", "FiscalYear"}

MARKER = "ZQ7X%sK3"          # unique per field, greppable, harmless

# Identity fields never receive a marker. Standing rule: no government ID goes into a target, and a
# marker in an identity slot risks creating a malformed identity record on a real tax product.
NEVER_MARK = {"pan", "aadhaarCardNumber", "enrollmentNumber", "tanOfEmployer",
              "directorIdentificationNumber", "ifscCode", "iFSCCode", "swiftCode"}


def fields_for(surface, input_name):
    """Every field of one INPUT_OBJECT, split into textual / coercing / other."""
    rows = [f for f in surface["inputs"] if f["input"] == input_name]
    out = {"textual": [], "coercing": [], "other": []}
    for f in rows:
        t = f["fieldType"]
        if t in TEXTUAL:
            out["textual"].append(f)
        elif t in COERCING:
            out["coercing"].append(f)
        else:
            out["other"].append(f)
    return out


def marker_object(split, base=None, include_coercing=False):
    """Build one input object with a unique marker in every textual field.

    Returns (obj, planted, skipped) — `skipped` names the identity fields deliberately left alone,
    so the coverage record shows them as excluded-by-policy rather than silently missing.
    """
    obj = dict(base or {})
    planted, skipped = {}, []
    for f in split["textual"]:
        name = f["field"]
        if name in NEVER_MARK:
            skipped.append(name)
            continue
        obj[name] = MARKER % name
        planted[name] = obj[name]
    if include_coercing:
        # A coercion probe, not an injection: does the parser accept text where a number belongs?
        for f in split["coercing"]:
            name = f["field"]
            if name in NEVER_MARK:
                skipped.append(name)
                continue
            obj[name] = MARKER % name
            planted[name] = obj[name]
    return obj, planted, skipped


